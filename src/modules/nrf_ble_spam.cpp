static uint8_t swapbits(uint8_t a) {
    uint8_t v = 0;
    if (a & 0x80) v |= 0x01; if (a & 0x40) v |= 0x02;
    if (a & 0x20) v |= 0x04; if (a & 0x10) v |= 0x08;
    if (a & 0x08) v |= 0x10; if (a & 0x04) v |= 0x20;
    if (a & 0x02) v |= 0x40; if (a & 0x01) v |= 0x80;
    return v;
}

static void bleWhiten(uint8_t* buf, uint8_t len, uint8_t ble_chan) {
    uint8_t lfsr = ble_chan | 0x40;
    while (len--) {
        uint8_t res = 0;
        for (uint8_t i = 1; i; i <<= 1) {
            if (lfsr & 0x01) { lfsr ^= 0x88; res |= i; }
            lfsr >>= 1;
        }
        *(buf++) ^= res;
    }
}

static void bleCRC(uint8_t* buf, uint8_t len, uint8_t* dst) {
    dst[0] = 0xAA; dst[1] = 0xAA; dst[2] = 0xAA;
    while (len--) {
        uint8_t d = *(buf++);
        for (uint8_t i = 1; i; i <<= 1, d >>= 1) {
            uint8_t t = dst[0] & 0x01;
            dst[0] >>= 1; if (dst[1] & 0x01) dst[0] |= 0x80;
            dst[1] >>= 1; if (dst[2] & 0x01) dst[1] |= 0x80;
            dst[2] >>= 1;
            if (t != (d & 1)) { dst[2] ^= 0xDA; dst[1] ^= 0x60; }
        }
    }
}

