// ---- IModule ----------------------------------------------------------------

bool NrfBleSpamModule::init() {
    if (!nrfLockSpi(pdMS_TO_TICKS(200))) {
        BLOG("[nrf_ble_spam] init: spi_mutex timeout\n");
        available_ = false;
        return false;
    }
    pinMode(PIN_NRF_CE,  OUTPUT); digitalWrite(PIN_NRF_CE,  LOW);
    pinMode(PIN_NRF_CSN, OUTPUT); digitalWrite(PIN_NRF_CSN, HIGH);
    delay(10);

    SPI.begin(PIN_SPI_SCK, PIN_SPI_MISO, PIN_SPI_MOSI);

    // Raw STATUS read before RF24::begin() to diagnose SPI wiring.
    // 0x0E = chip OK  0xFF = MISO floating  0x00 = MOSI/SCK issue
    SPI.beginTransaction(SPISettings(1000000, MSBFIRST, SPI_MODE0));
    digitalWrite(PIN_NRF_CSN, LOW);
    uint8_t rawStatus = SPI.transfer(0xFF);
    digitalWrite(PIN_NRF_CSN, HIGH);
    SPI.endTransaction();

    bool begun = g_nrf_radio.begin();
    bool chip  = begun && g_nrf_radio.isChipConnected();

    if (begun) {
        g_nrf_radio.setAutoAck(false);
        g_nrf_radio.setDataRate(RF24_1MBPS);
        g_nrf_radio.disableCRC();
        g_nrf_radio.setAddressWidth(4);
        g_nrf_radio.openWritingPipe(BLE_ADDR);
        g_nrf_radio.setPALevel(RF24_PA_MAX);
        g_nrf_radio.setRetries(0, 0);
        g_nrf_radio.stopListening();
        g_nrf_radio.powerDown();
    }
    nrfUnlockSpi();

    available_ = true;
    detected_  = chip;
    BLOG("[nrf_ble_spam] init: begin=%d chip=%d spiSTATUS=0x%02X\n", begun, chip, rawStatus);
    return true;
}

bool NrfBleSpamModule::isAvailable() { return true; }

void NrfBleSpamModule::start() {
    if (running_.exchange(true)) return;
    if (task_ != nullptr) { running_ = false; return; }
    // Always re-init so the chip is in BLE mode regardless of prior module.
    init();
    BLOG("[nrf_ble_spam] start (chip=%s)\n", detected_ ? "YES" : "NO");
    xTaskCreatePinnedToCore(bleSpamTask, "nrf_ble_sp", 8192, this, 1, &task_, 0);
}

void NrfBleSpamModule::stop() {
    if (!running_) return;
    BLOG("[nrf_ble_spam] stop\n");
    running_ = false;
    for (int i = 0; i < 50 && task_; ++i) {
        vTaskDelay(pdMS_TO_TICKS(10));
        eTaskState st = eTaskGetState(task_);
        if (st == eDeleted || st == eInvalid) break;
    }
    task_ = nullptr;
}

void NrfBleSpamModule::fillStats(char* buf, size_t len) {
    snprintf(buf, len, "%lu/s", (unsigned long)adv_per_sec_.load());
}
